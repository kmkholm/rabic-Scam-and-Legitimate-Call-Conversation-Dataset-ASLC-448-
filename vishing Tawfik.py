    cw = torch.tensor([len(y_tr)/(2*n0), len(y_tr)/(2*n1)], dtype=torch.float32).to(Config.DEVICE)
    crit = nn.CrossEntropyLoss(weight=cw)

    train_ds = ScamDataset(X_text_tr.tolist(), y_tr.tolist(), tokenizer, Config.MAX_LEN)
    val_ds = ScamDataset(X_text_val.tolist(), y_val.tolist(), tokenizer, Config.MAX_LEN)
    test_ds = ScamDataset(X_text_test.tolist(), y_test.tolist(), tokenizer, Config.MAX_LEN)

    train_dl = DataLoader(train_ds, batch_size=Config.BATCH_SIZE, shuffle=True)
    val_dl = DataLoader(val_ds, batch_size=Config.BATCH_SIZE)
    test_dl = DataLoader(test_ds, batch_size=Config.BATCH_SIZE)

    total_steps = len(train_dl) * Config.EPOCHS
    warmup_steps = int(total_steps * Config.WARMUP_RATIO)

    opt = torch.optim.AdamW(model.parameters(), lr=Config.LEARNING_RATE,
                             weight_decay=Config.WEIGHT_DECAY)
    # Cosine Annealing with warm restarts
    sch = torch.optim.lr_scheduler.CosineAnnealingWarmRestarts(opt, T_0=10, T_mult=2, eta_min=1e-7)

    best_val_f1, best_state = 0, None
    for epoch in range(Config.EPOCHS):
        model.train()
        for batch in train_dl:
            ids = batch['input_ids'].to(Config.DEVICE)
            mask = batch['attention_mask'].to(Config.DEVICE)
            lbl = batch['label'].to(Config.DEVICE)
            opt.zero_grad()
            out = model(input_ids=ids, attention_mask=mask)
            loss = crit(out.logits, lbl)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            opt.step()
            sch.step()

        # Validate every 5 epochs
        if (epoch + 1) % 5 == 0 or epoch == Config.EPOCHS - 1:
            model.eval()
            vp, vl = [], []
            with torch.no_grad():
                for batch in val_dl:
                    ids = batch['input_ids'].to(Config.DEVICE)
                    mask = batch['attention_mask'].to(Config.DEVICE)
                    out = model(input_ids=ids, attention_mask=mask)
                    vp.extend(torch.argmax(out.logits, dim=1).cpu().numpy())
                    vl.extend(batch['label'].numpy())
            vf1 = f1_score(vl, vp, average='weighted')
            if vf1 >= best_val_f1:
                best_val_f1 = vf1
                best_state = {k: v.cpu().clone() for k, v in model.state_dict().items()}
            if (epoch + 1) % 10 == 0:
                print(f"    Epoch {epoch+1:3d} | Val F1: {vf1:.4f} (best: {best_val_f1:.4f})")

    # Load best and predict test
    model.load_state_dict(best_state)
    model.to(Config.DEVICE)
    model.eval()
    s1_preds_f, s1_probs_f = [], []
    with torch.no_grad():
        for batch in test_dl:
            ids = batch['input_ids'].to(Config.DEVICE)
            mask = batch['attention_mask'].to(Config.DEVICE)
            out = model(input_ids=ids, attention_mask=mask)
            probs = torch.softmax(out.logits, dim=1)
            s1_preds_f.extend(torch.argmax(probs, dim=1).cpu().numpy())
            s1_probs_f.extend(probs[:, 1].cpu().numpy())
    s1_preds_f = np.array(s1_preds_f)
    s1_probs_f = np.array(s1_probs_f)
    print(f"  [S1] Fold {fold_idx+1} Test: Acc={accuracy_score(y_test, s1_preds_f):.4f} "
          f"F1={f1_score(y_test, s1_preds_f, average='weighted'):.4f}")
    del model; torch.cuda.empty_cache()

    # ──────────────── S2: Zero-Shot (with calibration) ────────────────
    print(f"  [S2] Zero-Shot (6 templates + Platt calibration)...")
    s2_test_raw = run_zsl(X_text_test.tolist(), zs_classifier, zs_templates,
                           template_weights, total_tw)
    s2_val_raw = run_zsl(X_text_val.tolist(), zs_classifier, zs_templates,
                          template_weights, total_tw)

    # Platt calibration
    platt = LogisticRegression(C=1.0, random_state=Config.SEED)
    platt.fit(s2_val_raw.reshape(-1, 1), y_val)
    s2_probs_f = platt.predict_proba(s2_test_raw.reshape(-1, 1))[:, 1]

    # Optimize threshold
    s2_val_cal = platt.predict_proba(s2_val_raw.reshape(-1, 1))[:, 1]
    best_thr = 0.5
    best_f1_t = 0
    for thr in np.arange(0.3, 0.7, 0.01):
        pf = f1_score(y_val, (s2_val_cal >= thr).astype(int), average='weighted')
        if pf > best_f1_t: best_f1_t = pf; best_thr = thr

    s2_preds_f = (s2_probs_f >= best_thr).astype(int)
    print(f"  [S2] Fold {fold_idx+1} Test: Acc={accuracy_score(y_test, s2_preds_f):.4f} "
          f"F1={f1_score(y_test, s2_preds_f, average='weighted'):.4f} (thr={best_thr:.2f})")

    # ──────────────── S3: Few-Shot kNN (20-shot) ────────────────
    print(f"  [S3] Few-Shot (20-shot, kNN on embeddings)...")
    emb_tr = all_embeddings[train_idx][tr_idx]
    emb_val = all_embeddings[train_idx][val_idx]
    emb_test = all_embeddings[test_idx]

    # Sample 20 per class (diverse)
    n_shot = 20
    fs_idx = []
    for lbl in [0, 1]:
        lbl_mask = np.where(y_tr == lbl)[0]
        if len(lbl_mask) > n_shot:
            chosen = np.random.choice(lbl_mask, n_shot, replace=False)
        else:
            chosen = lbl_mask
        fs_idx.extend(chosen)

    knn = KNeighborsClassifier(n_neighbors=min(n_shot, 7), metric='cosine', weights='distance')
    knn.fit(emb_tr[fs_idx], y_tr[fs_idx])

    s3_probs_f = knn.predict_proba(emb_test)[:, 1]
    s3_preds_f = knn.predict(emb_test)
    print(f"  [S3] Fold {fold_idx+1} Test: Acc={accuracy_score(y_test, s3_preds_f):.4f} "
          f"F1={f1_score(y_test, s3_preds_f, average='weighted'):.4f}")

    # ──────────────── S4: GBM ────────────────
    scaler = StandardScaler()
    Xf_tr = scaler.fit_transform(X_feat_tr)
    Xf_val = scaler.transform(X_feat_val)
    Xf_test = scaler.transform(X_feat_test)

    gb = GradientBoostingClassifier(n_estimators=200, max_depth=4, learning_rate=0.1,
                                     subsample=0.8, random_state=Config.SEED)
    gb.fit(Xf_tr, y_tr)
    s4_probs_f = gb.predict_proba(Xf_test)[:, 1]
