def apply_phone_filter(audio):
    audio = high_pass_filter(audio=300)
    audio = low_pass_filter(audio=3400)
    return audio

def add_background_noise(audio, noise_db=-35):
    duration_ms = len(audio)
    samples = np.random.normal(0, 1, int(audio.frame_rate * duration_ms / 1000))
    samples = (samples * 32767 * 0.01).astype(np.int16)
    noise = AudioSegment(samples.tobytes(), frame_rate=audio.frame_rate, sample_width=2, channels=1)
    noise = noise + noise_db
    if len(noise) < len(audio):
        noise = noise * (len(audio) // len(noise) + 1)
    noise = noise[:len(audio)]
    return audio.overlay(noise)

def normalize_audio(audio, target_dbfs=-20):
    change = target_dbfs - audio.dBFS
    return audio.apply_gain(change)

def vary_speed(audio):
    speed = random.uniform(0.95, 1.05)
    new_rate = int(audio.frame_rate * speed)
    return audio._spawn(audio.raw_data, overrides={"frame_rate": new_rate}).set_frame_rate(audio.frame_rate)

