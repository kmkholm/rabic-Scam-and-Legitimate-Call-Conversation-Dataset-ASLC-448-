# ══════════════════════════════════════════════════════════════
# CONFIG — Update these paths as needed
# ══════════════════════════════════════════════════════════════
WAV_FILE       = "333.wav"
MODEL_WEIGHTS  = "outputs/best_model.pt"      # from training script
BERT_NAME      = "aubmindlab/bert-base-arabertv2"
WHISPER_SIZE   = "large-v3"                    # tiny/base/small/medium/large-v3
THRESHOLD      = 0.5
MAX_LEN        = 256
DEVICE         = torch.device("cuda" if torch.cuda.is_available() else "cpu")

# ══════════════════════════════════════════════════════════════
# STEP 1: Load audio + ASR (Whisper)
# ══════════════════════════════════════════════════════════════
print("=" * 55)
print("  STEP 1: Speech-to-Text (Whisper)")
print("=" * 55)

import whisper

model_whisper = whisper.load_model(WHISPER_SIZE, device=DEVICE)
print(f"✓ Whisper {WHISPER_SIZE} loaded on {DEVICE}")

result = model_whisper.transcribe(WAV_FILE, language="ar", beam_size=5)
raw_text = result["text"]

print(f"✓ Transcription done")
print(f"  Language : {result.get('language', 'ar')}")
print(f"  Text     : {raw_text[:200]}")
print(f"  Words    : {len(raw_text.split())}")

# ══════════════════════════════════════════════════════════════
# STEP 2: Clean Arabic text
# ══════════════════════════════════════════════════════════════
print("\n" + "=" * 55)
print("  STEP 2: Text Cleaning")
print("=" * 55)

def clean_arabic(text):
    text = re.sub(r'[\u0617-\u061A\u064B-\u0652\u0670]', '', text)  # diacritics
    text = re.sub(r'\u0640', '', text)                                # tatweel
    text = re.sub(r'[إأآا]', 'ا', text)                              # normalize alef
    text = re.sub(r'(.)\1{2,}', r'\1\1', text)                       # elongation
    text = re.sub(r'\s+', ' ', text).strip()                         # whitespace
    return text

clean_text = clean_arabic(raw_text)
print(f"✓ Cleaned: {clean_text[:200]}")

# ══════════════════════════════════════════════════════════════
# STEP 3: Load fine-tuned AraBERT
# ══════════════════════════════════════════════════════════════
print("\n" + "=" * 55)
print("  STEP 3: Load AraBERT Classifier")
print("=" * 55)

from transformers import AutoTokenizer, AutoModelForSequenceClassification

tokenizer = AutoTokenizer.from_pretrained(BERT_NAME)
model_bert = AutoModelForSequenceClassification.from_pretrained(BERT_NAME, num_labels=2)
model_bert.load_state_dict(torch.load(MODEL_WEIGHTS, map_location=DEVICE))
model_bert.to(DEVICE)
model_bert.eval()
print(f"✓ AraBERT loaded with fine-tuned weights")

# ══════════════════════════════════════════════════════════════
# STEP 4: Classify
# ══════════════════════════════════════════════════════════════
print("\n" + "=" * 55)
print("  STEP 4: Classification")
print("=" * 55)

encoding = tokenizer(
    clean_text,
    max_length=MAX_LEN,
    padding="max_length",
    truncation=True,
    return_tensors="pt"
)

with torch.no_grad():
    outputs = model_bert(
        input_ids=encoding["input_ids"].to(DEVICE),
        attention_mask=encoding["attention_mask"].to(DEVICE)
    )
    probs = torch.softmax(outputs.logits, dim=1)[0]

not_scam_prob = probs[0].item()
scam_prob     = probs[1].item()
label         = "SCAM" if scam_prob >= THRESHOLD else "NOT_SCAM"

# Risk level
if   scam_prob >= 0.8: risk = "🔴 HIGH"
elif scam_prob >= 0.6: risk = "🟠 MEDIUM"
elif scam_prob >= 0.4: risk = "🟡 UNCERTAIN"
else:                  risk = "🟢 LOW"

# ══════════════════════════════════════════════════════════════
# RESULT
# ══════════════════════════════════════════════════════════════
print(f"""
{'=' * 55}
  {'🚨 SCAM DETECTED!' if label == 'SCAM' else '✅ CALL IS SAFE'}
{'=' * 55}
  Label            : {label}
  Scam Probability : {scam_prob:.4f} ({scam_prob:.1%})
  Safe Probability : {not_scam_prob:.4f} ({not_scam_prob:.1%})
  Risk Level       : {risk}
  Threshold        : {THRESHOLD}
{'─' * 55}
  Transcript:
  {clean_text[:300]}
{'=' * 55}
""")

