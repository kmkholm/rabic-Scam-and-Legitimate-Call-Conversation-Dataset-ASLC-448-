def extract_audio_features(audio_path, sr=SAMPLE_RATE):
    """Extract comprehensive audio features from WAV file."""
    try:
        y, sr = librosa.load(audio_path, sr=sr, mono=True)
    except Exception as e:
        print(f"  ⚠ Cannot load {audio_path}: {e}")
        return None

    duration = len(y) / sr

    # ── Basic features ──
    features = {
        "duration_sec": round(duration, 2),
        "n_samples": len(y),
        "rms_energy": float(np.sqrt(np.mean(y**2))),
        "zero_crossing_rate": float(np.mean(librosa.feature.zero_crossing_rate(y))),
    }

    # ── MFCC (13 coefficients — mean & std) ──
    mfcc = librosa.feature.mfcc(y=y, sr=sr, n_mfcc=13)
    for i in range(13):
        features[f"mfcc_{i+1}_mean"] = float(np.mean(mfcc[i]))
        features[f"mfcc_{i+1}_std"] = float(np.std(mfcc[i]))

    # ── Mel Spectrogram stats ──
    mel = librosa.feature.melspectrogram(y=y, sr=sr, n_mels=40)
    mel_db = librosa.power_to_db(mel, ref=np.max)
    features["mel_mean"] = float(np.mean(mel_db))
    features["mel_std"] = float(np.std(mel_db))
    features["mel_max"] = float(np.max(mel_db))

    # ── Spectral features ──
    spec_cent = librosa.feature.spectral_centroid(y=y, sr=sr)
    spec_bw = librosa.feature.spectral_bandwidth(y=y, sr=sr)
    spec_rolloff = librosa.feature.spectral_rolloff(y=y, sr=sr)

    features["spectral_centroid_mean"] = float(np.mean(spec_cent))
    features["spectral_bandwidth_mean"] = float(np.mean(spec_bw))
    features["spectral_rolloff_mean"] = float(np.mean(spec_rolloff))

    # ── Chroma ──
    chroma = librosa.feature.chroma_stft(y=y, sr=sr)
    features["chroma_mean"] = float(np.mean(chroma))
    features["chroma_std"] = float(np.std(chroma))

    # ── Tempo ──
    tempo, _ = librosa.beat.beat_track(y=y, sr=sr)
    features["tempo"] = float(tempo) if not hasattr(tempo, '__len__') else float(tempo[0])

    return features


