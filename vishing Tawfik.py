def predictor_for_shap(texts):
    # 1. Handle NumPy arrays (SHAP sends these)
    if hasattr(texts, 'tolist'):
        texts = texts.tolist()

    # 2. Handle Single String (Edge case)
    if isinstance(texts, str):
        texts = [texts]

    # 3. Tokenize (Now guaranteed to receive a List[str])
    inputs = tokenizer(texts, return_tensors="pt", padding=True, truncation=True, max_length=Config.MAX_LEN).to(Config.DEVICE)

    with torch.no_grad():
        outputs = model(**inputs)

    # 4. Return Logits
    return outputs.logits.cpu().numpy()

