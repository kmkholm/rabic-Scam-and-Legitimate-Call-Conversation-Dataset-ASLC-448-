    print(f"  [S4] Fold {fold_idx+1} Test: Acc={accuracy_score(y_test, s4_preds_f):.4f} "
          f"F1={f1_score(y_test, s4_preds_f, average='weighted'):.4f}")

    # ──────────────── S5: DAMSE Ensemble ────────────────
    # Get val probs for all strategies
    model_tmp = AutoModelForSequenceClassification.from_pretrained(
        Config.ARABERT_MODEL, num_labels=2)
    model_tmp.classifier.dropout = nn.Dropout(Config.DROPOUT)
    model_tmp.load_state_dict(best_state)
    model_tmp.to(Config.DEVICE); model_tmp.eval()
    s1_val_p = []
    with torch.no_grad():
        for batch in DataLoader(ScamDataset(X_text_val.tolist(), y_val.tolist(),
                                tokenizer, Config.MAX_LEN), batch_size=Config.BATCH_SIZE):
            out = model_tmp(input_ids=batch['input_ids'].to(Config.DEVICE),
                           attention_mask=batch['attention_mask'].to(Config.DEVICE))
            s1_val_p.extend(torch.softmax(out.logits, dim=1)[:, 1].cpu().numpy())
    s1_val_p = np.array(s1_val_p)
    del model_tmp; torch.cuda.empty_cache()

    s3_val_p = knn.predict_proba(emb_val)[:, 1]
    s4_val_p = gb.predict_proba(Xf_val)[:, 1]

    # Dialect-adaptive weights
    d_val = dialects[train_idx][val_idx]
    dw = {}
    for d in np.unique(d_test):
        m = d_val == d
        if m.sum() < 2:
            dw[d] = [0.40, 0.10, 0.15, 0.35]
            continue
        best_w, best_fd = None, 0
        for w1 in np.arange(0.2, 0.7, 0.1):
            for w2 in np.arange(0.05, 0.3, 0.05):
                for w3 in np.arange(0.05, 0.3, 0.05):
                    w4 = round(1.0 - w1 - w2 - w3, 2)
                    if w4 < 0.05 or w4 > 0.6: continue
                    fused = w1*s1_val_p[m] + w2*s2_val_cal[m] + w3*s3_val_p[m] + w4*s4_val_p[m]
                    fd = f1_score(y_val[m], (fused>=0.5).astype(int),
                                  average='weighted', zero_division=0)
                    if fd > best_fd: best_fd = fd; best_w = [w1, w2, w3, w4]
        dw[d] = best_w if best_w else [0.40, 0.10, 0.15, 0.35]

    # Apply DAMSE
    damse_probs_f = np.zeros(len(y_test))
    for i in range(len(y_test)):
        w = dw.get(d_test[i], [0.40, 0.10, 0.15, 0.35])
        damse_probs_f[i] = w[0]*s1_probs_f[i] + w[1]*s2_probs_f[i] + \
                            w[2]*s3_probs_f[i] + w[3]*s4_probs_f[i]
    damse_preds_f = (damse_probs_f >= 0.5).astype(int)
    print(f"  [S5] Fold {fold_idx+1} Test: Acc={accuracy_score(y_test, damse_preds_f):.4f} "
          f"F1={f1_score(y_test, damse_preds_f, average='weighted'):.4f}")

    # ──────────────── Store fold results ────────────────
    for sname, sp, sprob in [
        ("S1: AraBERT", s1_preds_f, s1_probs_f),
        ("S2: Zero-Shot", s2_preds_f, s2_probs_f),
        ("S3: Few-Shot", s3_preds_f, s3_probs_f),
        ("S4: GBM", s4_preds_f, s4_probs_f),
        ("S5: DAMSE", damse_preds_f, damse_probs_f),
    ]:
        fold_results[sname]['Accuracy'].append(accuracy_score(y_test, sp))
        fold_results[sname]['Precision'].append(precision_score(y_test, sp, average='weighted'))
        fold_results[sname]['Recall'].append(recall_score(y_test, sp, average='weighted'))
        fold_results[sname]['F1_W'].append(f1_score(y_test, sp, average='weighted'))
        fold_results[sname]['F1_M'].append(f1_score(y_test, sp, average='macro'))
        fold_results[sname]['MCC'].append(matthews_corrcoef(y_test, sp))
        fold_results[sname]['AUC_ROC'].append(roc_auc_score(y_test, sprob))
        fold_results[sname]['AUC_PR'].append(average_precision_score(y_test, sprob))

        all_fold_preds[sname][test_idx] = sp
        all_fold_probs[sname][test_idx] = sprob


