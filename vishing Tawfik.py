# Multi-template zero-shot: average across all label sets for robustness
def zero_shot_multi_template(texts, classifier, label_sets, batch_size=8):
    """Run zero-shot with multiple hypothesis templates and average results."""
    all_scores = np.zeros(len(texts))

    for set_name, labels in label_sets.items():
        print(f"    Running template: {set_name}...")
        scores = []
        for i in range(0, len(texts), batch_size):
            batch = texts[i:i+batch_size]
            results = classifier(batch, labels, multi_label=False)
            if not isinstance(results, list):
                results = [results]
            for r in results:
                # Score for the "scam" label (first label)
                scam_idx = r['labels'].index(labels[0])
                scores.append(r['scores'][scam_idx])

            if (i + batch_size) % 40 == 0 or i + batch_size >= len(texts):
                print(f"      [{min(i+batch_size, len(texts))}/{len(texts)}]")

        all_scores += np.array(scores)

    # Average across templates
    all_scores /= len(label_sets)
    return all_scores

