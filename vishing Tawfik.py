def enhanced_zero_shot(texts, classifier, label_sets, use_signals=True, batch_size=8):
    """
    IMPROVED zero-shot with:
    1. Scam signal extraction prepended to text
    2. Multiple hypothesis templates
    3. Weighted template averaging (Arabic templates get higher weight)
    """
    # Template weights: Arabic-specific templates weighted higher
    template_weights = {
        "ar_scam_direct": 1.5,
        "ar_social_eng":  1.3,
        "ar_bank_fraud":  1.2,
        "en_detailed":    0.8,
        "en_indicators":  0.7,
        "mixed_strong":   1.0,
    }
    total_weight = sum(template_weights.values())

    all_scores = np.zeros(len(texts))
    template_scores = {}

    for set_name, labels in label_sets.items():
        w = template_weights.get(set_name, 1.0)
        print(f"    Template: {set_name} (weight={w:.1f})...")
        scores = []

        for i in range(0, len(texts), batch_size):
            batch_texts = texts[i:i+batch_size]

            # IMPROVEMENT: Prepend scam signals for context
            if use_signals:
                batch_texts = [extract_scam_signals(t) for t in batch_texts]

            results = classifier(batch_texts, labels, multi_label=False)
            if not isinstance(results, list):
                results = [results]
            for r in results:
                scam_idx = r['labels'].index(labels[0])
                scores.append(r['scores'][scam_idx])

        scores = np.array(scores)
        template_scores[set_name] = scores
        all_scores += w * scores

    # Weighted average
    all_scores /= total_weight
    return all_scores, template_scores

