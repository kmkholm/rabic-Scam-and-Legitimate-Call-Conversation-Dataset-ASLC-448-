def convert_conversation(row, engine, temp_dir):
    """Convert one conversation to WAV."""
    conv_id = row['conversation_id']
    dialect = row['dialect']
    caller_voice, receiver_voice = engine.get_voices(dialect)
    voice_map = {"caller": caller_voice, "receiver": receiver_voice}

    segments = []
    for col_name, role in TURN_ORDER:
        text = str(row[col_name]).strip()
        if not text or text == "nan":
            continue

        temp_file = os.path.join(temp_dir, f"{conv_id}_{col_name}.wav")
        try:
            engine.synthesize(text, voice_map[role], temp_file)
            turn_audio = AudioSegment.from_file(temp_file)
            turn_audio = vary_speed(turn_audio)
            segments.append(turn_audio)
        except Exception as e:
            print(f"    ⚠ {conv_id}/{col_name}: {e}")
            continue

    if not segments:
        return None

    # Merge turns with silence
    silence = AudioSegment.silent(duration=SILENCE_MS)
    full_audio = segments[0]
    for seg in segments[1:]:
        full_audio = full_audio + silence + seg

    # Post-processing
    full_audio = normalize_audio(full_audio)
    if PHONE_FILTER:
        full_audio = apply_phone_filter(full_audio)
    if ADD_NOISE:
        full_audio = add_background_noise(full_audio, NOISE_DB)

    # Convert to 16kHz mono
    full_audio = full_audio.set_frame_rate(SAMPLE_RATE).set_channels(1).set_sample_width(2)

    # Save
    label_dir = os.path.join(OUTPUT_DIR, row['label'])
    os.makedirs(label_dir, exist_ok=True)
    output_path = os.path.join(label_dir, f"{conv_id}.wav")
    full_audio.export(output_path, format="wav")

    return output_path


