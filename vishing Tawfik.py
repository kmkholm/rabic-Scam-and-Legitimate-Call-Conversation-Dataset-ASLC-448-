# ═════════════════════════════════════════════════════════════════════════════
def extract_scam_signals(text):
    """Extract key scam indicators to prepend to conversation for ZSL context."""
    signals = []

    # Urgency patterns
    urgency_words = ['بسرعة', 'فوراً', 'حالاً', 'عاجل', 'آخر موعد', 'تنتهي', 'خلال ساعة',
                     'اليوم', 'الحين', 'قبل ما', 'ضروري']
    if any(w in text for w in urgency_words):
        signals.append("يوجد ضغط زمني")  # time pressure detected

    # Money patterns
    money_words = ['حوّل', 'ادفع', 'رسوم', 'مبلغ', 'ريال', 'دينار', 'فلوس', 'تحويل',
                   'حساب', 'عربون', 'استثمار', 'جائزة', 'ربحت']
    if any(w in text for w in money_words):
        signals.append("يوجد طلب مالي")  # financial request detected

    # Info request patterns
    info_words = ['رقم البطاقة', 'الرقم السري', 'رمز التحقق', 'رمز التأكيد', 'OTP',
                  'PIN', 'كلمة السر', 'بياناتك']
    if any(w in text for w in info_words):
        signals.append("طلب معلومات سرية")  # sensitive info request

    # Impersonation patterns
    impersonation_words = ['معك من البنك', 'شركة الاتصالات', 'مكتب الجوازات',
                           'الأحوال المدنية', 'الدعم الفني', 'البنك المركزي']
    if any(w in text for w in impersonation_words):
        signals.append("انتحال صفة جهة رسمية")  # impersonation detected

    # Threat patterns
    threat_words = ['إجراءات', 'تجميد', 'إيقاف', 'حيتوقف', 'غرامة', 'قانوني', 'مخالفة']
    if any(w in text for w in threat_words):
        signals.append("يوجد تهديد")  # threat detected

    if signals:
        prefix = " | ".join(signals) + " || "
        return prefix + text
    return text


